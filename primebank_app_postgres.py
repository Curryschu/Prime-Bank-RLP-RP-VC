import os
import secrets
import time
from functools import wraps
from urllib.parse import urlencode

import psycopg
from psycopg.rows import dict_row
import requests
from flask import Flask, g, redirect, request, session, url_for, render_template, flash

APP_SECRET = os.environ.get("SECRET_KEY")
if not APP_SECRET:
    raise RuntimeError("SECRET_KEY fehlt. Bitte in Render als Environment Variable setzen.")

DATABASE_URL = os.environ.get("DATABASE_URL")
if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL fehlt. Bitte die Supabase-Verbindung in Render als Environment Variable setzen.")

DISCORD_CLIENT_ID = os.environ.get("DISCORD_CLIENT_ID", "")
DISCORD_CLIENT_SECRET = os.environ.get("DISCORD_CLIENT_SECRET", "")
DISCORD_REDIRECT_URI = os.environ.get("DISCORD_REDIRECT_URI", "")
ADMIN_IDS = {x.strip() for x in os.environ.get("ADMIN_DISCORD_IDS", "").split(",") if x.strip()}
CURRENCY = os.environ.get("CURRENCY_NAME", "Night-Dollar")

app = Flask(
    __name__,
    template_folder="primebank/templates",
    static_folder="primebank/static"
)

app.secret_key = APP_SECRET
app.config.update(
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SECURE=os.environ.get("COOKIE_SECURE", "true").lower() == "true",
    SESSION_COOKIE_SAMESITE="Lax",
    PERMANENT_SESSION_LIFETIME=60 * 60 * 24 * 7,
)

def db():
    if "db" not in g:
        g.db = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=15)
    return g.db

@app.teardown_appcontext
def close_db(_error):
    conn = g.pop("db", None)
    if conn is not None:
        conn.close()

def init_db():
    with psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=15) as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                discord_id TEXT PRIMARY KEY,
                username TEXT NOT NULL,
                avatar TEXT,
                account_no TEXT UNIQUE NOT NULL,
                balance BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0)
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS transactions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                sender_id TEXT,
                receiver_id TEXT,
                amount BIGINT NOT NULL CHECK (amount > 0),
                note TEXT NOT NULL DEFAULT '',
                created_at BIGINT NOT NULL
            )
        """)

@app.before_request
def ensure_db():
    # CREATE TABLE IF NOT EXISTS is safe to run repeatedly; it also handles
    # the first request after a fresh deployment.
    init_db()

def current_user():
    uid = session.get("discord_id")
    if not uid:
        return None
    return db().execute("SELECT * FROM users WHERE discord_id = %s", (uid,)).fetchone()

def login_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if not session.get("discord_id"):
            flash("Bitte verbinde zuerst deinen Discord-Account.", "error")
            return redirect(url_for("index"))
        return fn(*args, **kwargs)
    return wrapper

def is_admin():
    return session.get("discord_id") in ADMIN_IDS

@app.route("/")
def index():
    user = current_user()
    if user:
        return redirect(url_for("dashboard"))
    return render_template("index.html")

@app.route("/login")
def login():
    if not all([DISCORD_CLIENT_ID, DISCORD_CLIENT_SECRET, DISCORD_REDIRECT_URI]):
        flash("Discord OAuth ist noch nicht vollständig konfiguriert.", "error")
        return redirect(url_for("index"))
    state = secrets.token_urlsafe(24)
    session["oauth_state"] = state
    params = {
        "client_id": DISCORD_CLIENT_ID,
        "redirect_uri": DISCORD_REDIRECT_URI,
        "response_type": "code",
        "scope": "identify",
        "state": state,
        "prompt": "consent",
    }
    return redirect("https://discord.com/oauth2/authorize?" + urlencode(params))

@app.route("/callback")
def callback():
    if request.args.get("state") != session.pop("oauth_state", None):
        flash("Sicherheitsprüfung fehlgeschlagen. Bitte erneut anmelden.", "error")
        return redirect(url_for("index"))
    code = request.args.get("code")
    if not code:
        flash("Discord-Anmeldung wurde abgebrochen.", "error")
        return redirect(url_for("index"))

    try:
        token_response = requests.post(
            "https://discord.com/api/oauth2/token",
            data={
                "client_id": DISCORD_CLIENT_ID,
                "client_secret": DISCORD_CLIENT_SECRET,
                "grant_type": "authorization_code",
                "code": code,
                "redirect_uri": DISCORD_REDIRECT_URI,
            },
            headers={"Content-Type": "application/x-www-form-urlencoded"},
            timeout=15,
        )
        if not token_response.ok:
            app.logger.error("Discord token exchange failed: %s", token_response.status_code)
            flash("Discord-Anmeldung fehlgeschlagen. OAuth-Einstellungen prüfen.", "error")
            return redirect(url_for("index"))
        access_token = token_response.json().get("access_token")
        profile_response = requests.get(
            "https://discord.com/api/users/@me",
            headers={"Authorization": f"Bearer {access_token}"},
            timeout=15,
        )
        if not profile_response.ok:
            flash("Discord-Profil konnte nicht geladen werden.", "error")
            return redirect(url_for("index"))
    except requests.RequestException:
        app.logger.exception("Discord OAuth request failed")
        flash("Discord ist gerade nicht erreichbar. Bitte später erneut versuchen.", "error")
        return redirect(url_for("index"))

    profile = profile_response.json()
    uid = str(profile["id"])
    username = profile.get("global_name") or profile.get("username") or "Discord Nutzer"
    avatar = profile.get("avatar")
    avatar_url = f"https://cdn.discordapp.com/avatars/{uid}/{avatar}.png?size=128" if avatar else None

    conn = db()
    existing = conn.execute(
        "SELECT account_no FROM users WHERE discord_id = %s", (uid,)
    ).fetchone()
    account_no = existing["account_no"] if existing else "PB" + secrets.token_hex(4).upper()
    with conn.transaction():
        conn.execute("""
            INSERT INTO users(discord_id, username, avatar, account_no, balance)
            VALUES(%s, %s, %s, %s, 0)
            ON CONFLICT(discord_id) DO UPDATE
            SET username = EXCLUDED.username, avatar = EXCLUDED.avatar
        """, (uid, username, avatar_url, account_no))

    session.clear()
    session["discord_id"] = uid
    session.permanent = True
    return redirect(url_for("dashboard"))

@app.route("/dashboard")
@login_required
def dashboard():
    user = current_user()
    txs = db().execute("""
        SELECT t.*, s.username AS sender_name, r.username AS receiver_name
        FROM transactions t
        LEFT JOIN users s ON s.discord_id = t.sender_id
        LEFT JOIN users r ON r.discord_id = t.receiver_id
        WHERE t.sender_id = %s OR t.receiver_id = %s
        ORDER BY t.created_at DESC LIMIT 12
    """, (user["discord_id"], user["discord_id"])).fetchall()
    return render_template("dashboard.html", user=user, txs=txs, currency=CURRENCY, admin=is_admin())

@app.route("/transfer", methods=["POST"])
@login_required
def transfer():
    token = session.get("csrf")
    if not token or request.form.get("csrf") != token:
        flash("Ungültige Anfrage. Bitte Seite neu laden.", "error")
        return redirect(url_for("dashboard"))

    recipient_no = request.form.get("account_no", "").strip().upper()
    try:
        amount = int(request.form.get("amount", "0"))
    except (TypeError, ValueError):
        amount = 0
    note = request.form.get("note", "").strip()[:120]
    if amount <= 0:
        flash("Bitte einen gültigen Betrag eingeben.", "error")
        return redirect(url_for("dashboard"))

    conn = db()
    try:
        with conn.transaction():
            sender = conn.execute(
                "SELECT * FROM users WHERE discord_id = %s FOR UPDATE",
                (session["discord_id"],)
            ).fetchone()
            receiver = conn.execute(
                "SELECT * FROM users WHERE account_no = %s FOR UPDATE",
                (recipient_no,)
            ).fetchone()

            if not sender:
                flash("Dein Bankkonto wurde nicht gefunden.", "error")
            elif not receiver:
                flash("Dieses Konto wurde nicht gefunden.", "error")
            elif receiver["discord_id"] == sender["discord_id"]:
                flash("Du kannst kein Geld an dich selbst senden.", "error")
            elif sender["balance"] < amount:
                flash("Dein Kontostand reicht dafür nicht aus.", "error")
            else:
                conn.execute(
                    "UPDATE users SET balance = balance - %s WHERE discord_id = %s",
                    (amount, sender["discord_id"])
                )
                conn.execute(
                    "UPDATE users SET balance = balance + %s WHERE discord_id = %s",
                    (amount, receiver["discord_id"])
                )
                conn.execute("""
                    INSERT INTO transactions(sender_id, receiver_id, amount, note, created_at)
                    VALUES(%s, %s, %s, %s, %s)
                """, (sender["discord_id"], receiver["discord_id"], amount, note, int(time.time())))
                flash(
                    f"{amount:,} {CURRENCY} wurden an {receiver['username']} überwiesen.".replace(",", "."),
                    "success"
                )
    except Exception:
        app.logger.exception("Transfer failed")
        flash("Überweisung fehlgeschlagen. Bitte erneut versuchen.", "error")
    return redirect(url_for("dashboard"))

@app.route("/admin", methods=["GET", "POST"])
@login_required
def admin():
    if not is_admin():
        flash("Du hast keinen Zugriff auf die Verwaltung.", "error")
        return redirect(url_for("dashboard"))

    if request.method == "POST":
        if request.form.get("csrf") != session.get("csrf"):
            flash("Ungültige Anfrage.", "error")
            return redirect(url_for("admin"))

        account_no = request.form.get("account_no", "").strip().upper()
        try:
            amount = int(request.form.get("amount", "0"))
        except (TypeError, ValueError):
            amount = 0
        action = request.form.get("action")
        target = db().execute(
            "SELECT * FROM users WHERE account_no = %s", (account_no,)
        ).fetchone()

        if not target or amount <= 0 or action not in ("add", "remove"):
            flash("Bitte Konto und positiven Betrag korrekt angeben.", "error")
        else:
            delta = amount if action == "add" else -amount
            conn = db()
            try:
                with conn.transaction():
                    updated = conn.execute("""
                        UPDATE users
                        SET balance = balance + %s
                        WHERE discord_id = %s AND balance + %s >= 0
                        RETURNING discord_id
                    """, (delta, target["discord_id"], delta)).fetchone()
                    if not updated:
                        flash("Das Konto hat nicht genügend Guthaben.", "error")
                    else:
                        conn.execute("""
                            INSERT INTO transactions(sender_id, receiver_id, amount, note, created_at)
                            VALUES(%s, %s, %s, %s, %s)
                        """, (
                            None if action == "add" else target["discord_id"],
                            target["discord_id"] if action == "add" else None,
                            amount,
                            "Verwaltung: Gutschrift" if action == "add" else "Verwaltung: Auszahlung",
                            int(time.time())
                        ))
                        flash("Kontostand wurde aktualisiert.", "success")
            except Exception:
                app.logger.exception("Admin balance update failed")
                flash("Kontostand konnte nicht aktualisiert werden.", "error")

    users = db().execute(
        "SELECT username, account_no, balance FROM users ORDER BY username"
    ).fetchall()
    return render_template("admin.html", users=users, currency=CURRENCY)

@app.route("/logout")
def logout():
    session.clear()
    return redirect(url_for("index"))

@app.template_filter("timestamp")
def format_timestamp(value):
    from datetime import datetime
    return datetime.fromtimestamp(int(value)).strftime("%d.%m.%Y · %H:%M")

@app.context_processor
def inject_globals():
    if "csrf" not in session:
        session["csrf"] = secrets.token_urlsafe(24)
    return {"csrf": session["csrf"], "logged_in": bool(session.get("discord_id"))}

if __name__ == "__main__":
    app.run(host="0.0.0.0", port=int(os.environ.get("PORT", 5000)))
